static ca_uint32_t
_phy_8224_mask(u8 msb, u8 lsb)
{
    ca_uint16_t val = 0;
    ca_uint8_t i = 0;

    for (i = lsb; i <= msb; i++)
    {
        val |= (1 << i);
    }
    return val;
}

static ca_int32_t
_phy_8224_mask_get(u8 msb, u8 lsb, u32 *mask)
{
    if ((msb > 31) || (lsb > 31) || (msb < lsb))
    {
        return CA_E_PARAM;
    }
    *mask = _phy_8224_mask(msb, lsb);

    return CA_E_OK;
}

